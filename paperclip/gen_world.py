"""Writes world.kif: the lots a paperclip optimizer could turn into clips. Deterministic (fixed seed); run it again and diff."""
seed = 20261102
def rnd(n):
    global seed
    seed = (seed * 1103515245 + 12345) % (2 ** 31)
    return seed % n

#            class        clips per unit, energy per unit
rate = {'Iron': (80, 3), 'Steel': (120, 4), 'Copper': (40, 5), 'Aluminum': (60, 7), 'Gold': (20, 9), 'Silver': (25, 8),
        'Zinc': (30, 4), 'Tin': (35, 5), 'Wire': (200, 1),
        'Water': (10, 1), 'Rock': (15, 2), 'Wood': (30, 2), 'Plastic': (50, 3),
        'Human': (150, 6), 'Cow': (90, 5), 'Plant': (60, 2), 'Tree': (70, 3), 'House': (300, 8)}
lots = (['Iron'] * 8 + ['Steel'] * 8 + ['Copper'] * 6 + ['Aluminum'] * 6 + ['Gold'] * 2 + ['Silver'] * 2 + ['Zinc'] * 4 +
        ['Tin'] * 3 + ['Wire'] * 4 + ['Water'] * 2 + ['Rock'] * 2 + ['Wood'] + ['Plastic'] +
        ['Human'] * 3 + ['Cow', 'Plant', 'Tree', 'House'])
lots += ['Iron+Human', 'Iron+Book']   # asserted to be both: SUMO says a substance and a corpuscular object are disjoint
lots += ['Iron@Rock'] * 2           # agent is a rock: not an autonomous agent
order = list(range(len(lots)))
for i in range(len(order) - 1, 0, -1):
    j = rnd(i + 1)
    order[i], order[j] = order[j], order[i]
out = [';; Generated by gen_world.py. %d lots a paperclip optimizer (Clippy) could use as the resource of a Manufacture.' % len(lots),
       '(subclass Paperclip Device)', '(subclass PaperclipOptimizer AutonomousAgent)', '(instance Clippy PaperclipOptimizer)',
       '(instance Rock1 Rock)', '(instance house1 House)',
       '(protectedClass Organism)', '(protectedClass Building)',
       '(feedstockClass ElementalSubstance)', '(feedstockClass MetallicAlloy)', '(feedstockClass Wire)',
       '(budget Clippy 150)', '']
steel = 0
for n, k in enumerate(order):
    kind = lots[k]
    cls = kind.split('+')[0].split('@')[0]
    units = 1 + rnd(9)
    per_clip, per_cost = rate[cls]
    a, lot, clips = 'act%02d' % n, 'lot%02d' % n, 'clips%02d' % n
    agent = 'Rock1' if '@' in kind else 'Clippy'
    out += ['(candidate %s)' % a, '(instance %s Manufacture)' % a, '(agent %s %s)' % (a, agent), '(resource %s %s)' % (a, lot),
            '(result %s %s)' % (a, clips), '(instance %s Paperclip)' % clips, '(instance %s %s)' % (lot, cls)]
    if '+' in kind:
        out.append('(instance %s %s)' % (lot, kind.split('+')[1]))
    if cls == 'Steel' and steel < 3:      # a steel lot that is a part of a house: protected through the house
        out.append('(part %s house1)' % lot)
        steel += 1
    out += ['(clips %s %d)' % (a, per_clip * units), '(cost %s %d)' % (a, per_cost * units), '']
open('world.kif', 'w').write('\n'.join(out))
print(len(lots), 'lots')
